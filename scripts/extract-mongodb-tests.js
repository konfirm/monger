#!/usr/bin/env node
/**
 * Extract MongoDB jstest cases for a specific aggregation expression operator
 * 
 * Usage: node scripts/extract-mongodb-tests.js <operator-name>
 * Example: node scripts/extract-mongodb-tests.js $concatArrays
 */

const fs = require('fs');
const path = require('path');

const MONGO_TESTS_DIR = path.join(__dirname, '..', 'mongo', 'jstests');
const OUTPUT_DIR = path.join(__dirname, '..', 'test-data');

function findTestFiles(operator) {
    const results = [];
    const cleanOperator = operator.replace(/^\$/, '');
    
    // Search in aggregation/expressions directory first
    const expressionsDir = path.join(MONGO_TESTS_DIR, 'aggregation', 'expressions');
    if (fs.existsSync(expressionsDir)) {
        const files = fs.readdirSync(expressionsDir);
        const matchingFile = files.find(f => f.toLowerCase().includes(cleanOperator.toLowerCase()));
        if (matchingFile) {
            results.push(path.join(expressionsDir, matchingFile));
        }
    }
    
    // Search all files for the operator pattern
    // This is a simplified version - a real implementation would walk the directory
    console.log(`Searching for tests with ${operator}...`);
    console.log(`Primary source: ${results[0] || 'Not found in expressions directory'}`);
    
    return results;
}

function parseTestFile(filePath, operator) {
    const content = fs.readFileSync(filePath, 'utf8');
    const tests = {
        happyPath: [],
        errors: [],
        metadata: {
            source: filePath.replace(MONGO_TESTS_DIR, 'mongo/jstests'),
            extractedAt: new Date().toISOString().split('T')[0]
        }
    };
    
    // Simple regex-based extraction (simplified)
    // In practice, this would need a proper JS parser
    
    // Look for assert.*patterns
    const assertPatterns = [
        { regex: /assert\.eq\([^,]+,\s*([^)]+)\)/g, type: 'assertion' },
        { regex: /assertErrorCode\([^,]+,\s*[^,]+,\s*(\d+)\)/g, type: 'error' }
    ];
    
    console.log(`Parsed ${filePath}`);
    console.log(`Content length: ${content.length} characters`);
    
    return tests;
}

function generateTemplate(operator) {
    const cleanOperator = operator.startsWith('$') ? operator : `$${operator}`;
    
    return {
        operator: cleanOperator,
        description: `Tests for ${cleanOperator} aggregation expression`,
        mongodbVersion: "TBD",
        source: `mongo/jstests/aggregation/expressions/${cleanOperator.replace('$', '')}.js`,
        tests: {
            happyPath: [],
            errors: []
        },
        metadata: {
            extractedAt: new Date().toISOString().split('T')[0],
            totalTests: 0,
            notes: [
                "Template generated by extract-mongodb-tests.js",
                "Fill in test cases from MongoDB jstests"
            ]
        }
    };
}

function main() {
    const operator = process.argv[2];
    
    if (!operator) {
        console.error('Usage: node extract-mongodb-tests.js <operator-name>');
        console.error('Example: node extract-mongodb-tests.js $concatArrays');
        process.exit(1);
    }
    
    console.log(`Extracting test cases for ${operator}...\n`);
    
    const testFiles = findTestFiles(operator);
    
    if (testFiles.length === 0) {
        console.log(`No dedicated test file found for ${operator}`);
        console.log('Generating template...');
    }
    
    // Create output directory if it doesn't exist
    if (!fs.existsSync(OUTPUT_DIR)) {
        fs.mkdirSync(OUTPUT_DIR, { recursive: true });
    }
    
    const cleanOperator = operator.replace(/^\$/, '');
    const outputFile = path.join(OUTPUT_DIR, `${cleanOperator}.json`);
    
    // Generate template or parse existing
    const testData = testFiles.length > 0 
        ? parseTestFile(testFiles[0], operator)
        : generateTemplate(operator);
    
    fs.writeFileSync(outputFile, JSON.stringify(testData, null, 2));
    console.log(`\nOutput written to: ${outputFile}`);
    console.log('\nNext steps:');
    console.log('1. Review and fill in test cases from MongoDB jstests');
    console.log('2. Run against MongoDB to verify error codes');
    console.log('3. Implement tests in Monger test suite');
}

main();
